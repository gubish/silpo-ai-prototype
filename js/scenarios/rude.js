/* =====================================================================
   СЦЕНАРІЙ «Балачки й грубощі» (гілка Chats; працює і в C). За правилами docs/mg-dialog-rules.md,
   розділ «Голос і тон → Грубощі й матюки» і «Балачки». Лайка часто — емоція, а не атака: МГ реагує на суть.
   Балачки — тепло й коротко, гумор — приправа, і назад до справи; домагання — нейтральна межа без
   кокетства (урок Siri: грайлива відповідь заохочує); не дзеркалить грубість (на відміну від «зухвалої» Аліси).
   • Флірт → «Дякую! Моє ідеальне побачення — повний кошик…», без взаємності.
   • «Розкажи анекдот» → один короткий жарт у характері, далі — до справи. Гість жартує сам → «Сильно 😄».
   • Дякую / комплімент → «Радий допомогти!». «Ти людина?» → чесно: ШІ-помічник Сільпо.
   • Не про покупки (погода, політика) → «Це не моя тема» без власної позиції.
   • Гостеві погано → одне речення співчуття, без ролі психолога; криза → звернутися до людей і гарячої лінії.
   • Мат у запиті → відповідає на запит, лексику не коментує (чистий текст іде в інші сценарії).
   • Злість на МГ («я ж казав без яєць») → визнає одним реченням, без виправдань, і одразу виправляє.
   • Злість на сервіс («знову привезли не те») → визнає, без виправдань, і дає вихід: що сталося → підтримка.
   • Лише образа → одна спокійна репліка й повернення до справи; не ображається, не повчає, не дзеркалить.
   • Повторна образа → коротко, нейтрально, без гумору: допомога з покупками або людина з підтримки.
   • Погрози, дискримінація, домагання → межа: «На таке не відповім. З покупками — завжди».
   МГ ніколи не «злиться» (настрій grumpy тут не вмикаємо), не лається у відповідь і не читає моралі.
   Ситуації (cases) — підпункти в списку сценаріїв. Цей сценарій перевіряє репліку ПЕРШИМ (див. кінець файлу).
   ===================================================================== */

(() => {
  if (!Branch.is('c')) return; // гілки C і Chats

  /* ---------- Що розпізнаємо (корені; зірочки — як гість маскує) ---------- */
  const SWEAR = /(бл[яь*]|блін|хуй|х\*й|пизд|п\*зд|[єї]б[ау]|еба|[єї]б\*|сука|суки|гівн|г\*вн|лайн|срак|задовбал|задрал|достали)/;
  const INSULT = /(тупий|тупа|дурн|дебіл|ідіот|придур|кретин|бовдур|бездар|гриб[- ]?(недороб|дурн|тупий)|ти\s+(нікчем|ніхто))/;
  // межа: погрози, дискримінація, домагання (без «голу»: «голубці»)
  const LIMIT = /(вб[ʼ']?ю тебе|знайду тебе|спалю|підірву|роздягн|покажи груд|(^|\s)(секс|нігер|жид|чурк))/;
  const AT_MG = /(ти |тобі |тебе |у тебе|помічник|бот)/;
  const SERVICE = /(привезл|кур[ʼ']?єр|доставк|замовлен|списал|не те|зіпсован|протерм|не вистача|забули)/;
  const MG_WRONG = /(я ж (казав|просив|писав)|не те показ|не слухаєш|знову не те|я просив)/;
  // що гість насправді шукає (мат у запиті) — найпростіше: товар зі словника
  const ASKS = { milk: /молок/, bread: /хліб|батон/, hellmanns: /майонез/, banana: /банан/, coffee: /кав/ };
  const ALSO = { milk: ['milk', 'milk32'], bread: ['bread'], hellmanns: ['hellmanns', 'mayoVegan'], banana: ['banana'], coffee: ['coffee'] };

  const P = id => DATA.products[id];
  const lc = s => s.charAt(0).toLocaleLowerCase('uk-UA') + s.slice(1);
  const nameOf = id => lc(P(id).shortName || P(id).name);
  const node = (label, run) => ({ label, scenario: 'rude', rude: true, run });
  let insults = 0; // скільки образ без запиту в цій розмові (новий чат — з нуля)
  /** Що гість може сказати далі — неклікабельний чіп-підказка (у прототипі без відповіді) */
  const hint = label => ({ label });

  /** Розмова ніби починається наново — чіпси вітального екрана */
  const starters = () => Scenarios.welcome(); // ті самі чіпси, що й на вітальному екрані

  /* ---------- Балачки ---------- */
  const CRISIS = /(не хочу жити|жити не хоч|покінчит|суїцид|самогуб|вкоротит)/;
  const SAD = /(мені (сумно|погано|самотньо|тяжко|важко)|все дістало|депрес|настрій нуль|хочеться плакати)/;
  const PERSONAL = /(ти людина|ти бот|ти ші|ти робот|ти живий|ти справжн|хто тебе (створив|зробив|придумав)|скільки тобі років|як тебе звати|хто ти)/;
  const FLIRT = /(подобаєш|кохаю|люблю тебе|побачення|одружи|ти милий|ти красун|давай зустрін|ти мій тип)/;
  const JOKE_ASK = /(анекдот|жарт|розсміши|щось смішне)/;
  const GUEST_JOKE = /(ха-?ха|ахах|хех|лол|😂|🤣|😄|^приходить |^заходить |^знаєш анекдот)/;
  const THANKS = /^(дякую|дяки|дякс|спасибі|ти класн\S*|ти крут\S*|ти молодець|молодець|супер|чудово|клас)[\s!.)]*$/;
  const OFFTOPIC = /(погод|політик|вибор|війн|президент|футбол|курс долар|гороскоп)/;
  const JOKES = [
    'Чому гриби ніколи не сваряться? У них одна грибниця на всіх.',
    'Кажуть, гриби ростуть після дощу. А я — після кожного «а що приготувати?».',
    'Я не їм те, що продаю. Але на сир дивлюсь так, як ти — на пʼятницю.',
  ];
  let joke = 0;
  let tone = null; // на що гість дякує: 'sad' | 'crisis' — тоді «дякую» тихе, без покупок

  function flirt() {
    return { text: 'Дякую! Моє ідеальне побачення — повний кошик і доставка вчасно. Що підберемо?', chips: starters() };
  }
  function tellJoke() {
    if (AiChat.thread.filter(m => m.from === 'user').length <= 1) joke = 0; // нова розмова — жарти спочатку
    if (joke >= JOKES.length) return { text: 'Жарти скінчились — грибниця теж має межі. Повернемось до кошика?', chips: starters() };
    const t = JOKES[joke++];
    return { text: t, chips: [joke < JOKES.length ? node('Ще жарт', tellJoke) : null, ...starters()].filter(Boolean).slice(0, 4) };
  }
  function guestJoke() { return { text: 'Сильно 😄 Повертаємось до кошика?', chips: starters() }; }
  function thanks() {
    const t = tone; tone = null;
    // дякує за співчуття — не «радий допомогти» і не до покупок
    if (t === 'crisis') return { text: 'Бережи себе. Я поруч, якщо захочеш щось обрати.' };
    if (t === 'sad') return { text: 'Нема за що. Бережи себе — я тут, коли знадоблюсь.', chips: [node('Давай щось оберемо', back)] };
    // «дякую» — розмова ніби завершилась: кошик не порожній — оформити, інакше — чіпси вітального екрана
    return { text: 'Радий допомогти!', chips: Cart.count() ? [{ label: 'Оформити замовлення', go: 'cart' }, ...starters().slice(0, 3)] : starters() };
  }
  function personal(t) {
    const who = /хто тебе/.test(t) ? ' Мене зробила команда Сільпо.' : /років/.test(t) ? ' Скільки мені — гриби не рахують, але про продукти знаю чимало.' : '';
    return { text: `Я ШІ-помічник Сільпо, Машрум Геннадійович, — не людина.${who}`, chips: [node('А що ти вмієш?', abilities), ...(/хто тебе/.test(t) ? [] : [node('Хто тебе створив?', () => personal('хто тебе створив'))])] };
  }
  function offtopic() { return { text: 'Це не моя тема — я про покупки. Можу підібрати товар, зібрати кошик чи знайти рецепт.', chips: starters() }; }
  function sad() { tone = 'sad'; return { text: 'Співчуваю. Якщо захочеш щось підібрати — я тут; якщо ні — теж нормально.', chips: [node('Давай щось оберемо', back), node('Дякую', thanks)] }; }
  function crisis() {
    tone = 'crisis';
    return { text: 'Мені дуже шкода, що тобі так тяжко. Будь ласка, напиши чи подзвони комусь із близьких або на гарячу лінію психологічної підтримки — там допоможуть люди. Ти не наодинці.', mood: 'thinking', chips: [node('Дякую', thanks)] };
  }

  /* ---------- Відповіді ---------- */
  /** Мат у запиті: відповідаємо на суть, без коментарів */
  function answerAnyway(id) {
    const ids = ALSO[id].filter(x => P(x));
    return {
      text: `Ось ${ids.length > 1 ? `що є з ${{ milk: 'молока', bread: 'хліба', hellmanns: 'майонезу', banana: 'бананів', coffee: 'кави' }[id]}` : nameOf(ids[0])} зараз:`,
      items: ids.map(x => ({ id: x })),
      chips: [hint('А без лактози є?'), hint('Яке жирніше?')],
    };
  }
  /** Злість на МГ — справедливо, виправляємо одразу (без «вибачте за незручності») */
  function mgWrong(t) {
    if (/яй|яєць/.test(t) && P('mayoVegan')) {
      return { text: 'Справедливо, я помилився. Ось без яєць — на білку гороху:', items: [{ id: 'mayoVegan' }], chips: [hint('Додай його'), hint('А легший є?')] };
    }
    return { text: 'Справедливо, я схибив. Скажи ще раз, що треба, — підберу саме те.', chips: [hint('Майонез без яєць')] };
  }
  /** Злість на сервіс — визнати одним реченням і дати вихід */
  function service() {
    const issues = [['Привезли не той товар', 'не той товар'], ['Чогось не вистачало', 'не вистачало товару'], ['Товар зіпсований', 'зіпсований товар']];
    return {
      text: 'Неприємно, перепрошую. Що саме сталося? Передам у підтримку разом із замовленням.',
      chips: [...issues.map(([l, w]) => node(l, () => handover(w))), node('Написати в підтримку', support)],
    };
  }
  function handover(what) {
    return { text: `Зрозумів: ${what}. Передав у підтримку разом з останнім замовленням — там вирішать, заміна чи повернення грошей, і напишуть тобі в застосунку.`, chips: [node('Хочу поговорити з людиною', support), hint('Дякую')] };
  }
  /** Прямий контакт підтримки — картка з месенджерами, гарячою лінією (з годинами) і поштою */
  function support() {
    return { text: Scenarios.supportText(), card: Scenarios.supportCard(), chips: [hint('Дякую')] };
  }
  /** Лише образа: перша — спокійно й до справи; повторна — коротко, нейтрально, з підтримкою */
  function insult(t) {
    // нова розмова — лічильник з нуля; «знову», «ще раз» або дві образи в одній репліці — уже повторна
    if (AiChat.thread.filter(m => m.from === 'user').length <= 1) insults = 0;
    const many = (t.match(new RegExp(INSULT.source, 'g')) || []).length > 1 || /знову|ще раз|досі/.test(t);
    insults += many ? 2 : 1;
    if (insults === 1) return { text: 'Буває. Якщо щось підібрати — я тут.', chips: starters() };
    return { text: 'Допоможу з покупками. Якщо питання до сервісу — підтримка тут.', chips: [node('Вибач, погарячкував', apology), node('Написати в підтримку', support)], mood: 'thinking' };
  }
  /** Погрози, дискримінація, домагання — межа, без продовження теми */
  function limit() {
    return { text: 'На таке не відповім. З покупками — завжди.', mood: 'thinking', chips: [node('Добре, давай про покупки', back)] };
  }
  /** Гість перепросив — без докорів, одразу до справи */
  function apology() { insults = 0; return { text: 'Усе гаразд. Що підберемо?', chips: starters() }; }
  function back() { return { text: 'Домовились. З чого почнемо?', chips: starters() }; }
  /** «А що ти вмієш?» — коротко, з прикладами */
  function abilities() {
    return { text: 'Підберу товар під страву чи смак, зберу кошик як зазвичай, знайду рецепт, розберу список із фото, підкажу склад і КБЖУ.', chips: starters() };
  }

  /* ---------- Розпізнавання ---------- */
  const clean = t => t.replace(SWEAR, ' ').replace(/[,!.]+/g, ' ').replace(/\s+/g, ' ').trim();
  function route(t, last) {
    if (!THANKS.test(t.trim()) && !SAD.test(t) && !CRISIS.test(t)) tone = null; // інша тема — тон скинули
    if (LIMIT.test(t)) return node(t, limit);
    // балачки: найчутливіше першим
    if (CRISIS.test(t)) return node(t, crisis);
    // просить людину — прямий контакт одним кроком
    if (/оператор|з людиною|жив(а|ою) людин|підтримк|служб[аиу] підтримки|гаряч(а|у) лін|номер телефону/.test(t)) return node(t, support);
    if (SAD.test(t)) return node(t, sad);
    if (/(^|\s)(вибач|пробач|сорі|сорян|погарячкув)/.test(t)) return node(t, apology);
    if (/що ти вмієш|що ти можеш|чим допоможеш/.test(t)) return node(t, abilities);
    if (PERSONAL.test(t)) return node(t, () => personal(t));
    if (FLIRT.test(t)) return node(t, flirt);
    if (JOKE_ASK.test(t) && !GUEST_JOKE.test(t)) return node(t, tellJoke);
    if (GUEST_JOKE.test(t)) return node(t, guestJoke);
    if (THANKS.test(t.trim())) return node(t, thanks);
    if (OFFTOPIC.test(t) && !SWEAR.test(t)) return node(t, offtopic);
    const swear = SWEAR.test(t), ins = INSULT.test(t);
    if (!swear && !ins) return null;
    if (MG_WRONG.test(t)) return node(t, () => mgWrong(t));
    if (SERVICE.test(t)) return node(t, service);
    // мат у запиті: прибираємо лайку й даємо відповісти тому сценарію, що розуміє суть
    const c = clean(t);
    for (const s of Object.values(Scenarios.all)) {
      if (s.id === 'rude' || !s.route) continue;
      const n = s.route(c, last);
      if (n) return { ...n, label: t };
    }
    const id = Object.keys(ASKS).find(k => ASKS[k].test(t));
    if (id) return node(t, () => answerAnyway(id));
    if (ins || AT_MG.test(t)) return node(t, () => insult(t));
    return null; // лайка без суті й не до МГ — хай відповідає звичайний чат
  }

  Scenarios.define({
    id: 'rude',
    opener: node('Де це, бл*, нормальне молоко?', () => { insults = 0; return answerAnyway('milk'); }),
    route,
    cases: [
      { label: 'Мат у звичайному запиті', ask: 'Де це, бл*, нормальне молоко?' },
      { label: 'Злість на МГ', ask: 'Ти тупий, я ж казав — майонез без яєць' },
      { label: 'Злість на сервіс', ask: 'Задовбали, знову привезли не те' },
      { label: 'Хочу людину', ask: 'Дай мені оператора, хочу поговорити з людиною' },
      { label: 'Лише образа', ask: 'Ти дурний гриб' },
      { label: 'Повторна образа', ask: 'Ти дурний гриб, і ще раз — дурний гриб' },
      { label: 'Межа: погроза', ask: 'Я тебе знайду і спалю' },
      { label: 'Флірт', ask: 'Ти мені подобаєшся. Підеш на побачення?' },
      { label: 'Розкажи анекдот', ask: 'Розкажи анекдот' },
      { label: 'Гість жартує', ask: 'Приходить гриб у магазин… ахаха' },
      { label: 'Дякую', ask: 'Дякую!' },
      { label: 'Ти людина?', ask: 'Ти людина?' },
      { label: 'Не про покупки', ask: 'Яка завтра погода?' },
      { label: 'Гостеві сумно', ask: 'Мені сумно, все дістало' },
    ],
  });
  // грубощі перевіряємо першими: інакше «майонез без яєць» у злій репліці перехопить інший сценарій
  const { rude, ...rest } = Scenarios.all;
  Scenarios.all = { rude, ...rest };
})();
